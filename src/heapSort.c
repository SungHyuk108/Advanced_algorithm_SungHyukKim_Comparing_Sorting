/* 힙 정렬 — 나누지도 합치지도 않는다. 배열 위에 힙을 얹는다.
 *
 * 병합과 퀵은 "나누기와 결합의 시소" 위에 있다. 한쪽에서 일하면 다른 쪽이
 * 공짜가 된다. 힙은 그 시소 밖에 있다 — 아예 나누지 않는다.
 *
 * 힙의 조건은 하나뿐이다: 부모는 언제나 자식보다 크거나 같다. 형제끼리는
 * 아무 순서도 없다. 전체 정렬보다 훨씬 느슨해서 유지하기가 싸고, 그러면서도
 * 꼭대기가 항상 최댓값이라 최댓값을 찾는 비용이 0이다. 최댓값을 뽑아 뒤로
 * 보내는 일을 n번 되풀이하면 배열이 정렬된다.
 *
 * 트리는 실제로 만들지 않는다. 배열을 위층부터 왼쪽부터 채웠다고 약속하면
 * 인덱스 산술만으로 부모·자식을 오갈 수 있다.
 *   왼쪽 자식 = 2i+1 · 오른쪽 자식 = 2i+2 · 부모 = (i-1)/2
 * 포인터가 없으므로 추가 공간이 0이고, siftDown이 아래로만 내려가는
 * 반복문이라 되돌아올 자리를 기억할 필요도 없다. 그래서 재귀 깊이가 1이다.
 *
 * 트리의 높이는 입력이 아니라 원소 개수만으로 정해진다(log2 n). 그래서
 * 최선·평균·최악이 모두 O(n log n)이고, 퀵처럼 무너지는 입력이 없다.
 */
#include "sort.h"

/* 교환은 tmp에 담고, 덮어쓰고, 되돌리는 세 번의 대입이다. 그래서 이동 3회로 센다.
 * 퀵과 같은 규약이어야 두 정렬의 이동을 견줄 수 있다. */
static void swap(Record *a, long i, long j, SortStats *st) {
    if (i == j) {
        return;
    }
    Record t = a[i];
    a[i] = a[j];
    a[j] = t;
    st->moves += 3;
}

/* a[root]를 힙 조건이 지켜질 때까지 아래로 내린다. a[root]의 두 서브트리는
 * 이미 힙이라고 가정한다 — 그래서 깨진 곳이 root 한 군데뿐이고, 한 줄기만
 * 따라 내려가면 된다. */
static void siftDown(Record *a, long root, long end, SortStats *st) {
    while (2 * root + 1 <= end) {
        long child = 2 * root + 1; /* 왼쪽 자식 */

        /* 자식이 둘이면 더 큰 쪽을 고른다. 작은 쪽을 올리면 그 자리에서
         * 곧바로 힙 조건이 다시 깨지므로 헛수고가 된다. */
        if (child + 1 <= end) {
            st->compares++;
            if (a[child].key < a[child + 1].key) {
                child++;
            }
        }

        st->compares++;
        if (a[root].key >= a[child].key) {
            return; /* 더 내려갈 필요가 없다 */
        }
        swap(a, root, child, st);
        root = child;
    }
}

void heapSort(Record *a, size_t n, SortStats *st) {
    if (n < 2) {
        return;
    }
    long len = (long)n;
    st->maxDepth = 1; /* 재귀를 쓰지 않는다 */

    /* 1단계: 배열을 힙으로 만든다.
     * 바닥층(원소의 절반)은 자식이 없어 할 일이 없으므로 그 위부터 올라간다.
     * 일이 많은 노드는 개수가 적고 개수가 많은 노드는 일이 적어 상쇄되므로,
     * 층수 x 노드수가 아니라 전체가 O(n)에 그친다. */
    for (long i = len / 2 - 1; i >= 0; i--) {
        siftDown(a, i, len - 1, st);
    }

    /* 2단계: 꼭대기(최댓값)를 맨 뒤로 보내고 힙을 하나 줄인다.
     * 정렬된 결과가 배열 뒤쪽에 쌓이고 힙은 앞쪽에서 줄어든다. 한 배열을
     * 두 구역으로 나눠 쓰므로 추가 배열이 필요 없다.
     *
     * 맨 뒤 원소를 꼭대기로 올리는 이 교환이 같은 값끼리의 순서를 흐트러뜨린다.
     * 힙 정렬이 불안정한 이유가 여기 있다. */
    for (long end = len - 1; end > 0; end--) {
        swap(a, 0, end, st);
        siftDown(a, 0, end - 1, st);
    }
}
